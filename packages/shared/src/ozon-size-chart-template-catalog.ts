function text(value: unknown): string {
  return String(value || '').normalize('NFKC').replace(/\s+/g, ' ').trim();
}

function headerKey(row: OzonSizeChartTemplateRow): string {
  const first = text(row.header[0]);
  const second = text(row.header[1]);
  return second && second !== first ? `${first} / ${second}` : first;
}

function normalizeToken(value: string): string {
  return text(value)
    .replace(/[()\[\]{}【】]/g, ' ')
    .replace(/\b(\d+)\s*XL\b/gi, '$1XL')
    .replace(/,/g, '.')
    .replace(/\s+/g, '')
    .toUpperCase();
}

function aliases(value: string): string[] {
  const base = normalizeToken(value);
  const parts = base.split(/[\/\|]+/).filter(Boolean);
  const out = new Set([base, ...parts]);
  const alpha: Record<string, string[]> = {
    '2XL': ['XXL'],
    '3XL': ['XXXL'],
    '4XL': ['XXXXL'],
    '5XL': ['XXXXXL'],
    '6XL': ['XXXXXXL'],
    '7XL': ['XXXXXXXL'],
    '8XL': ['XXXXXXXXL'],
    XXL: ['2XL'],
    XXXL: ['3XL'],
    XXXXL: ['4XL'],
    XXXXXL: ['5XL'],
  };
  for (const item of [...out]) {
    for (const alias of alpha[item] || []) out.add(alias);
  }
  return [...out].filter(Boolean);
}

function isPreferredMatchRow(row: OzonSizeChartTemplateRow): boolean {
  const key = headerKey(row);
  return /^(RU|INT|EU|UK|US)(?:\b|\s|\/)|Размер|Российский размер|Международный размер|Европейский размер|Американский размер|Английский размер|Рост|Возраст|Длина стопы|Обхват головы|Размер рамы/i.test(key);
}

function isSizeIdentityMatchRow(row: OzonSizeChartTemplateRow): boolean {
  const key = headerKey(row);
  return /^(RU|INT|EU|UK|US)(?:\b|\s|\/)|^Размер(?:\b|\s|\/)|Российский размер|Международный размер|Европейский размер|Американский размер|Английский размер|Размер рамы/i.test(key);
}

function numberInCellRange(cell: string, rawSize: string): boolean {
  const wanted = normalizeToken(rawSize).match(/\d{1,3}(?:\.\d+)?/)?.[0];
  if (!wanted) return false;
  const value = Number(wanted);
  if (!Number.isFinite(value)) return false;
  for (const match of text(cell).matchAll(/(\d{1,3}(?:[,.]\d+)?)\s*(?:-|–|—|~|до)\s*(\d{1,3}(?:[,.]\d+)?)/gi)) {
    const from = Number(String(match[1] || '').replace(',', '.'));
    const to = Number(String(match[2] || '').replace(',', '.'));
    if (Number.isFinite(from) && Number.isFinite(to) && value >= Math.min(from, to) && value <= Math.max(from, to)) return true;
  }
  return false;
}

function exactRowIndexForSize(template: OzonSizeChartTemplate, rawSize: string): number | null {
  const exact = normalizeToken(rawSize);
  const rows = [
    ...template.body.filter(isSizeIdentityMatchRow),
    ...template.body.filter((row) => !isSizeIdentityMatchRow(row)),
  ];
  for (const row of rows) {
    for (let index = 0; index < row.values.length; index += 1) {
      if (normalizeToken(row.values[index] || '') === exact) return index;
    }
  }
  return null;
}

function braCompositeCupIndexes(template: OzonSizeChartTemplate, rawSize: string): number[] {
  if (template.profile !== 'bra' && template.key !== 'bra') return [];
  const indexes = new Set<number>();
  for (const token of aliases(rawSize)) {
    const match = token.match(/^(\d{2,3})([A-Z]{2,})$/);
    if (!match) continue;
    const band = match[1];
    const cups = match[2];
    if (!band || !cups) continue;
    for (const cup of [...cups]) {
      const index = exactRowIndexForSize(template, `${band}${cup}`);
      if (index != null) indexes.add(index);
    }
  }
  return [...indexes];
}

function rowIndexesForSize(template: OzonSizeChartTemplate, rawSize: string): number[] {
  const compositeCupIndexes = braCompositeCupIndexes(template, rawSize);
  if (compositeCupIndexes.length > 0) return compositeCupIndexes;

  const exactIndex = exactRowIndexForSize(template, rawSize);
  if (exactIndex != null) return [exactIndex];

  const wanted = new Set(aliases(rawSize));
  const rows = [
    ...template.body.filter(isPreferredMatchRow),
    ...template.body.filter((row) => !isPreferredMatchRow(row)),
  ];
  for (const row of rows) {
    for (let index = 0; index < row.values.length; index += 1) {
      if (numberInCellRange(row.values[index] || '', rawSize)) return [index];
    }
  }
  for (const row of rows) {
    for (let index = 0; index < row.values.length; index += 1) {
      const cellAliases = aliases(row.values[index] || '');
      if (cellAliases.some((alias) => wanted.has(alias))) return [index];
    }
  }
  return [];
}

function applyKnownFields(row: OzonSizeChartBuildRow, key: string, value: string) {
  if ((/^(?:RU|RU \/|RU рост)/i.test(key) || /Российский размер/i.test(key)) && !row.ruSize) row.ruSize = value;
  if ((/^INT\b|Международный размер/i.test(key)) && !row.intSize) row.intSize = value;
  if ((/Длина стопы|Длина следа|^Дс(?:1)?\b/i.test(key)) && !row.footLengthCm) row.footLengthCm = value;
  if (/Длина стельки|^Дс2\b/i.test(key)) row.insoleLengthCm = value;
  if (/Примечание/i.test(key)) row.note = value;
}

export function getOzonSizeChartTemplateByProfile(profile: string): OzonSizeChartTemplate | null {
  const key = PROFILE_ALIASES[text(profile).toLowerCase()] || text(profile).toLowerCase();
  return OZON_SIZE_CHART_TEMPLATES.find((template) => template.profile === key || template.key === key) || null;
}

export function buildOzonSizeChartRows(sizes: string[], profile: string): OzonSizeChartBuildResult {
  const template = getOzonSizeChartTemplateByProfile(profile);
  if (!template) return { title: '', columns: [], rows: [] };
  const columns = template.body.map(headerKey).filter(Boolean);
  const rows: OzonSizeChartBuildRow[] = [];
  const seenIndexes = new Set<number>();
  for (const size of sizes.map(text).filter(Boolean)) {
    for (const index of rowIndexesForSize(template, size)) {
      if (seenIndexes.has(index)) continue;
      seenIndexes.add(index);
      const out: OzonSizeChartBuildRow = { size: normalizeToken(size) || size };
      for (const sourceRow of template.body) {
        const key = headerKey(sourceRow);
        const value = text(sourceRow.values[index]);
        if (!key || !value) continue;
        out[key] = value;
        applyKnownFields(out, key, value);
      }
      rows.push(out);
    }
  }
  return { title: template.title, columns, rows };
}
